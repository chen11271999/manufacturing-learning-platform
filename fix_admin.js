for (let i = 0; i < lines.length; i++) {
  if (lines[i].trim() === 'function initAdmin() {') {
    start = i;
    let braceCount = 0;
    for (let j = i; j < lines.length; j++) {
      braceCount += (lines[j].match(/{/g) || []).length;
      braceCount -= (lines[j].match(/}/g) || []).length;
      if (braceCount === 0 && j > i) { end = j + 1; break; }
    }
    break;
  }
}

